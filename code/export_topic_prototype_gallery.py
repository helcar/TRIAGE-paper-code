"""Show FIT-partition image regions associated with a recovered-error topic.

For each --case, reconstruct its original, frozen-config prototype dictionary
and NMF topics from FIT only. Read the recovered-case JSON generated by
plot_recovered_qualitative.py to identify the TOP contributing topic for a
recovered high-confidence false negative, and its top 3 weighted prototypes.
Locate high-polarity-attribution grid cells assigned to these prototypes
in different FIT groups, then show 64px local image crops around each cell.

Crucial: image crops are grid-cell-localized examples, NOT the detector's
full receptive fields or confirmed deepfake artifacts. Topic indices and
prototype identities are dataset-specific and have no shared semantics.
No test features or test images are opened; the recovered-case JSON is only
used to specify the preselected topic/prototype identifiers.
"""
import argparse
import csv
import json
import math
import warnings
from dataclasses import asdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from PIL import Image
from sklearn.exceptions import ConvergenceWarning

from .run_experiment import read
from .triage import Config, TRIAGE
from .validate_triage import prototype_matrices


def rows_fit(path):
    with open(path,encoding="utf-8-sig",newline="") as f:
        rows=[r for r in csv.DictReader(f) if r["split"]=="fit"]
    if not rows or not {"path","label"}.issubset(rows[0]):
        raise ValueError(f"Expected nonempty FIT manifest with path/label: {path}")
    return rows


def fit_model(args,fit):
    cfg=Config(prototypes=args.prototypes,topics_positive=args.topics,
               topics_negative=args.topics,
               references_real=args.references,
               references_fake=args.references,tau=args.tau,
               lambda_support=args.lambda_support,
               lambda_oppose=args.lambda_oppose,
               lambda_magnitude=args.lambda_magnitude,
               max_local_features=args.max_local_features,seed=args.seed)
    model=TRIAGE(cfg)
    b=args.batch
    model.fit_prototypes(fit["features"][i:i+b]
                         for i in range(0,len(fit["labels"]),b))
    pp,nn=prototype_matrices(model,fit,b)
    with warnings.catch_warnings(record=True) as ws:
        warnings.simplefilter("always",ConvergenceWarning)
        model.fit_topics(pp,nn)
    converg=[str(w.message) for w in ws
             if issubclass(w.category,ConvergenceWarning)]
    return model,converg


def read_target(summary_path,dataset):
    report=json.loads(Path(summary_path).read_text(encoding="utf-8"))
    if dataset not in report.get("datasets",{}):
        raise ValueError(f"Dataset {dataset!r} absent from {summary_path}")
    entry=report["datasets"][dataset]["selected_case"]
    if (entry["true_label"]!=1 or entry["predicted_label"]!=0 or
        entry["confidence"]<.90 or not entry["in_global_top10pct"]):
        raise ValueError("Target must be a recovered high-confidence false negative")
    if not entry.get("top_topics"):
        raise ValueError("Recovered-case JSON has no ranked topics")
    topic=entry["top_topics"][0]
    return entry,int(topic["topic"]),entry["plotted_polarity"],topic


def validate_proto_order(model,polarity,topic_id,source_topic):
    if polarity not in ("+","-"):
        raise ValueError("Unknown polarity")
    comp=model.nmf[polarity].components_[topic_id]
    col=model.columns[polarity]
    order=np.argsort(-comp,kind="stable")
    protos=[(int(col[k]),float(comp[k])) for k in order[:3]]
    original=source_topic.get("highest_weight_prototypes",[])
    expected=[int(x["prototype"]) for x in original[:3]]
    if [p for p,_ in protos]!=expected:
        raise RuntimeError(
            f"Topic/prototype reconstruction disagrees with recovered "
            f"JSON: fitted={[p for p,_ in protos]}, exported={expected}. "
            "Do not use inconsistent visualizations.")
    return protos


def find_cells(model,fit,rows,protos,polarity,batch):
    feats=fit["features"]
    attrs=fit["attributions"]
    target=set(int(p) for p,_ in protos)
    candidates={p:[] for p in target}
    for start in range(0,len(rows),batch):
        stop=min(len(rows),start+batch)
        xx=np.asarray(feats[start:stop],dtype=np.float32).copy()
        n,t,d=xx.shape
        norm=np.maximum(np.linalg.norm(xx,axis=-1,keepdims=True),1e-12)
        xx/=norm
        assign=model.prototypes.predict(xx.reshape(-1,d)).reshape(n,t)
        attr=np.asarray(attrs[start:stop],dtype=float)
        strength=np.maximum(attr,0) if polarity=="+" else np.maximum(-attr,0)
        for p in target:
            mask=assign==p
            scores=np.where(mask,strength,-1)
            token_idx=np.argmax(scores,axis=1)
            score=scores[np.arange(n),token_idx]
            for k in np.flatnonzero(score>0):
                ix=start+int(k)
                candidates[p].append({
                    "fit_index":ix,"token_index":int(token_idx[k]),
                    "signed_attribution_strength":float(score[k]),
                    "group_id":rows[ix].get("group_id") or rows[ix]["path"],
                    "path":rows[ix]["path"],
                })
    selected={}
    for p in target:
        ranked=sorted(candidates[p],
                      key=lambda x:(-x["signed_attribution_strength"],x["fit_index"]))
        chosen=[]
        groups=set()
        for r in ranked:
            if r["group_id"] not in groups:
                chosen.append(r)
                groups.add(r["group_id"])
            if len(chosen)==2:
                break
        if len(chosen)<2:
            raise ValueError(f"Not enough distinct FIT groups expressing "
                             f"prototype {p} with polarity {polarity}")
        selected[p]=chosen
    return selected


def crop_cell(path,token,t,patch_px):
    side=math.isqrt(t)
    if side*side!=t:
        raise ValueError(f"Cannot map {t} tokens to a square grid")
    with Image.open(path) as im:
        image=np.asarray(im.convert("RGB").resize((256,256)))
    rr,cc=divmod(token,side)
    cx=(cc+.5)*256/side
    cy=(rr+.5)*256/side
    x0=int(max(0,min(256-patch_px,round(cx-patch_px/2))))
    y0=int(max(0,min(256-patch_px,round(cy-patch_px/2))))
    return image[y0:y0+patch_px,x0:x0+patch_px],{
        "grid_row":int(rr),"grid_col":int(cc),
        "crop_box_xywh":[x0,y0,patch_px,patch_px],
        "token_grid_side":side
    }


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--case",nargs=13,action="append",required=True,
                   metavar=("DATASET","FIT","MANIFEST","IMAGE_ROOT","K","M","J",
                            "TAU","LAMBDA_SUPPORT","LAMBDA_OPPOSE",
                            "LAMBDA_MAGNITUDE","SEED","MAX_LOCAL_FEATURES"))
    p.add_argument("--recovered-json",required=True)
    p.add_argument("--output-pdf",required=True)
    p.add_argument("--output-png",required=True)
    p.add_argument("--output-json",required=True)
    p.add_argument("--batch",type=int,default=64)
    p.add_argument("--patch-px",type=int,default=80)
    a=p.parse_args()
    if a.patch_px<16 or a.patch_px>256 or a.batch<1:
        p.error("Invalid patch size or batch size")
    n=len(a.case)
    fig,axes=plt.subplots(n,6,figsize=(13.8,3.2*n),squeeze=False)
    outputs={}
    for row_no,fields in enumerate(a.case):
        (dataset,fitpath,manifestpath,root,k,m,j,tau,lam_s,
         lam_o,lam_m,seed,maxlocal)=fields
        if dataset in outputs:
            raise ValueError(f"Duplicate dataset {dataset}")
        config=argparse.Namespace(
            prototypes=int(k),topics=int(m),references=int(j),
            tau=float(tau),lambda_support=float(lam_s),
            lambda_oppose=float(lam_o),lambda_magnitude=float(lam_m),
            seed=int(seed),max_local_features=int(maxlocal),batch=a.batch)
        rows=rows_fit(manifestpath)
        fit=read(fitpath)
        if len(rows)!=len(fit["labels"]):
            raise ValueError(f"{dataset}: FIT row count mismatch")
        labels=np.asarray([int(x["label"]) for x in rows])
        if not np.array_equal(labels,np.asarray(fit["labels"])):
            raise ValueError(f"{dataset}: FIT labels not aligned")
        recovered,topic_id,polarity,source_topic=read_target(
            a.recovered_json,dataset)
        model,convergence=fit_model(config,fit)
        protos=validate_proto_order(model,polarity,topic_id,source_topic)
        candidates=find_cells(model,fit,rows,protos,polarity,a.batch)
        n_tokens=int(fit["attributions"].shape[1])
        records=[]
        for pi,(proto,weight) in enumerate(protos):
            for example_index,rec in enumerate(candidates[proto]):
                path=Path(rec["path"])
                if not path.is_absolute():
                    path=Path(root)/path
                if not path.is_file():
                    raise FileNotFoundError(path)
                image,geometry=crop_cell(path,rec["token_index"],n_tokens,
                                         a.patch_px)
                ax=axes[row_no,2*pi+example_index]
                ax.imshow(image)
                ax.set_xticks([])
                ax.set_yticks([])
                ax.set_title(f"P{proto} (w={weight:.2g}) | "
                             f"FIT region {example_index+1}",fontsize=8)
                rec={**rec,**geometry,
                     "prototype":proto,"nmf_topic_weight":weight}
                records.append(rec)
        axes[row_no,0].set_ylabel(
            f"{dataset}\nTopic {topic_id} "
            f"({'FAKE' if polarity=='+' else 'REAL'} evidence)",
            fontsize=10)
        outputs[dataset]={
            "source_recovered_test_index":recovered["test_index"],
            "source_outcome":"recovered false negative",
            "selected_topic":topic_id,
            "polarity":polarity,
            "prototypes":protos,"fit_region_examples":records,
            "nmf_convergence_warnings":convergence,
            "scope":"FIT only for all displayed regions; recovered TEST case only names topic"
        }
        print(f"{dataset}: selected topic T{topic_id} "
              f"polarity={polarity} with prototypes {[p for p,_ in protos]}")
    fig.suptitle("Top-weighted prototypes: actual local FIT image regions "
                 "(not verified manipulation artifacts)",fontsize=12)
    fig.text(.5,.015,
             "80px crops around block8 token-grid cells; visual cell "
             "location is not the complete neural receptive field.",
             fontsize=8,ha="center")
    fig.tight_layout(rect=(0,.035,1,.95))
    for name in ("output_pdf","output_png","output_json"):
        Path(getattr(a,name)).parent.mkdir(parents=True,exist_ok=True)
    fig.savefig(a.output_pdf,bbox_inches="tight")
    fig.savefig(a.output_png,dpi=170,bbox_inches="tight")
    plt.close(fig)
    Path(a.output_json).write_text(json.dumps({
        "protocol":"FIT-only local region examples from highest-weight prototypes",
        "image_crop_width_px":a.patch_px,
        "datasets":outputs
    },indent=2),encoding="utf-8")
    print(f"Saved {a.output_pdf}, {a.output_png}, {a.output_json}")


if __name__=="__main__":
    main()
